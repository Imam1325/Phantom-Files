def set_document_style(doc: Document) -> None:
    style = doc.styles['Normal']
    style.font.name = 'Times New Roman'
    style.font.size = Pt(14)
    style._element.rPr.rFonts.set(qn('w:eastAsia'), 'Times New Roman')
    style.paragraph_format.line_spacing = 1.5
    style.paragraph_format.space_after = Pt(0)
    style.paragraph_format.space_before = Pt(0)
    style.paragraph_format.first_line_indent = Cm(1.25)

    for name in ['Heading 1', 'Heading 2']:
        h = doc.styles[name]
        h.font.name = 'Times New Roman'
        h.font.size = Pt(14)
        h.font.bold = True
        h._element.rPr.rFonts.set(qn('w:eastAsia'), 'Times New Roman')
        h.paragraph_format.line_spacing = 1.5
        h.paragraph_format.space_after = Pt(0)
        h.paragraph_format.space_before = Pt(0)
        h.paragraph_format.first_line_indent = Cm(1.25)
        h.paragraph_format.alignment = WD_PARAGRAPH_ALIGNMENT.LEFT

    section = doc.sections[0]
    section.top_margin = Cm(2)
    section.bottom_margin = Cm(2)
    section.left_margin = Cm(3)
    section.right_margin = Cm(1.5)

    section.different_first_page_header_footer = True
    footer = section.footer
    p = footer.paragraphs[0]
    p.alignment = WD_PARAGRAPH_ALIGNMENT.CENTER
    run = p.add_run()
    fld_char_begin = OxmlElement('w:fldChar')
    fld_char_begin.set(qn('w:fldCharType'), 'begin')
    instr_text = OxmlElement('w:instrText')
    instr_text.set(qn('xml:space'), 'preserve')
    instr_text.text = 'PAGE'
    fld_char_separate = OxmlElement('w:fldChar')
    fld_char_separate.set(qn('w:fldCharType'), 'separate')
    fld_char_end = OxmlElement('w:fldChar')
    fld_char_end.set(qn('w:fldCharType'), 'end')
    run._r.append(fld_char_begin)
    run._r.append(instr_text)
    run._r.append(fld_char_separate)
    run._r.append(fld_char_end)


def add_centered_title(doc: Document, text: str, bold: bool = True) -> None:
    p = doc.add_paragraph()
    p.alignment = WD_PARAGRAPH_ALIGNMENT.CENTER
    p.paragraph_format.first_line_indent = Cm(0)
    run = p.add_run(text)
    run.bold = bold


def add_structural_heading(doc: Document, text: str) -> None:
    p = doc.add_paragraph()
    p.alignment = WD_PARAGRAPH_ALIGNMENT.CENTER
    p.paragraph_format.first_line_indent = Cm(0)
    run = p.add_run(text.upper())
    run.bold = True


def add_heading_1(doc: Document, text: str) -> None:
    doc.add_paragraph(text, style='Heading 1')


def add_heading_2(doc: Document, text: str) -> None:
    doc.add_paragraph(text, style='Heading 2')


def add_text_block(doc: Document, text: str) -> None:
    for para in [p.strip() for p in text.split('\n\n') if p.strip()]:
        p = doc.add_paragraph(para)
        p.paragraph_format.first_line_indent = Cm(1.25)


def add_code_block(doc: Document, text: str) -> None:
    for line in text.splitlines():
        p = doc.add_paragraph(line)
        p.paragraph_format.first_line_indent = Cm(0)
        for run in p.runs:
            run.font.name = 'Courier New'
            run.font.size = Pt(11)
            run._element.rPr.rFonts.set(qn('w:eastAsia'), 'Courier New')


def add_term_list(doc: Document, items: list[tuple[str, str]]) -> None:
    for term, definition in items:
        p = doc.add_paragraph(f"{term} - {definition}")
        p.paragraph_format.first_line_indent = Cm(0)


def add_abbrev_list(doc: Document, items: list[tuple[str, str]]) -> None:
    for abbr, definition in items:
        p = doc.add_paragraph(f"{abbr} - {definition}")
        p.paragraph_format.first_line_indent = Cm(0)


def add_toc(doc: Document) -> None:
    p = doc.add_paragraph()
    p.paragraph_format.first_line_indent = Cm(0)
    run = p.add_run()
    fld_char_begin = OxmlElement('w:fldChar')
    fld_char_begin.set(qn('w:fldCharType'), 'begin')
    instr_text = OxmlElement('w:instrText')
    instr_text.set(qn('xml:space'), 'preserve')
    instr_text.text = 'TOC \\o "1-2" \\h \\z \\u'
    fld_char_separate = OxmlElement('w:fldChar')
    fld_char_separate.set(qn('w:fldCharType'), 'separate')
    fld_char_end = OxmlElement('w:fldChar')
    fld_char_end.set(qn('w:fldCharType'), 'end')
    run._r.append(fld_char_begin)
    run._r.append(instr_text)
    run._r.append(fld_char_separate)
    run._r.append(fld_char_end)


def add_table(doc: Document, title: str, headers: list[str], rows: list[list[str]]) -> None:
    p = doc.add_paragraph(title)
    p.paragraph_format.first_line_indent = Cm(0)
    p.paragraph_format.alignment = WD_PARAGRAPH_ALIGNMENT.LEFT

    table = doc.add_table(rows=1, cols=len(headers))
    table.style = 'Table Grid'
    hdr_cells = table.rows[0].cells
    for i, h in enumerate(headers):
        hdr_cells[i].text = h

    for row in rows:
        cells = table.add_row().cells
        for i, cell_text in enumerate(row):
            cells[i].text = cell_text

    for row in table.rows:
        for cell in row.cells:
            for p in cell.paragraphs:
                for run in p.runs:
                    run.font.name = 'Times New Roman'
                    run.font.size = Pt(12)
                    run._element.rPr.rFonts.set(qn('w:eastAsia'), 'Times New Roman')


